import importlib.util
import json
import os
import tempfile
import threading
import time
from datetime import datetime, timezone
from http.server import HTTPServer
from urllib.request import Request, urlopen

PATH = os.path.join(os.path.dirname(__file__), 'sports-control', 'server.py')
SPEC = importlib.util.spec_from_file_location('sports_control_server', PATH)
SERVER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SERVER)

assert SERVER.clean('São Paulo') == 'sao paulo'
assert SERVER.parse_xmltv_time('20261023170000 -0300') == datetime(2026, 10, 23, 20, 0, tzinfo=timezone.utc).timestamp()

now = time.time()
SERVER.EPG_CACHE['epg.xml'] = (now, [
    {'channelId': 'sportv-2', 'channel': 'SporTV 2', 'start': now - 1800, 'stop': now + 9000,
     'title': 'Campeonato Brasileiro: São Paulo x Santos', 'subtitle': '', 'description': 'Partida ao vivo.'},
    {'channelId': 'premiere', 'channel': 'Premiere', 'start': now - 1800, 'stop': now + 9000,
     'title': 'Palmeiras x Flamengo', 'subtitle': '', 'description': 'Partida ao vivo.'},
    {'channelId': 'old', 'channel': 'Canal antigo', 'start': now - 86400, 'stop': now - 82000,
     'title': 'São Paulo x Santos', 'subtitle': '', 'description': ''},
])
matches = SERVER.event_epg_candidates('epg.xml', now, 'São Paulo', 'Santos')
assert len(matches) == 1
assert matches[0]['channel'] == 'SporTV 2'
assert matches[0]['matchedTeams'] == 2

game = {'id': 'soccer/bra.1:test', 'title': 'São Paulo x Santos', 'competition': 'Brasileirão',
        'sportName': 'Futebol', 'home': 'São Paulo', 'away': 'Santos', 'start': now * 1000,
        'broadcasts': []}
programme = {'channelId': 'sportv', 'channel': 'SporTV', 'start': now - 300,
             'stop': now + 7200, 'title': 'Campeonato Brasileiro: São Paulo x Santos',
             'subtitle': '', 'description': '', 'source': 'epg.xml'}
predicted = SERVER.forecast_game(game, [programme], set(), 75)
assert predicted['status'] == 'review'
assert predicted['confidence'] >= 75
assert predicted['candidates'][0]['channel'] == 'SporTV'
assert predicted['candidates'][0]['percentKind'] == 'initial-match-score'
stale = SERVER.forecast_game(game, [programme], {'epg.xml'}, 75)
assert stale['status'] == 'review'
assert stale['confidence'] < 75

weak = dict(programme, title='Futebol ao vivo')
weak_forecast = SERVER.forecast_game(game, [weak], set(), 75)
assert weak_forecast['status'] == 'review'
assert weak_forecast['confidence'] > 0

tie = dict(programme, channelId='premiere', channel='Premiere')
tied_forecast = SERVER.forecast_game(game, [programme, tie], set(), 75)
assert tied_forecast['status'] == 'review'

observations = []
for event_index in range(80):
    event_id = 'event-%03d' % event_index
    recorded = '2026-01-%02dT00:00:00' % (event_index % 28 + 1)
    observations.append({'eventId': event_id, 'recordedAt': recorded, 'label': 1,
        'features': {'bothTeams': 1, 'oneTeam': 0, 'timeFit': 1, 'sportsSource': 1, 'espnBrazil': 0, 'freshEpg': 1}})
    observations.append({'eventId': event_id, 'recordedAt': recorded, 'label': 0,
        'features': {'bothTeams': 0, 'oneTeam': 0, 'timeFit': 0.2, 'sportsSource': 0, 'espnBrazil': 0, 'freshEpg': 1}})
model, model_info = SERVER.train_model(observations)
assert model is not None and model_info['mode'] == 'calibrated'
assert model_info['brier'] < model_info['baselineBrier']
probability = SERVER.forecast_game(game, [programme], set(), 75, {}, model, model_info)
assert probability['status'] == 'approved'
assert probability['candidates'][0]['percentKind'] == 'probability'
assert SERVER.forecast_game(game, [programme], {'epg.xml'}, 75, {}, model, model_info)['status'] == 'review'

original_read_state = SERVER.read_state
SERVER.read_state = lambda: {'threshold': 75, 'reviewed': {game['id']: {'action': 'confirm', 'channel': 'SporTV'}}}
manual = SERVER.forecast_game(game, [], set(), 75)
assert manual['status'] == 'manual-confirmed'
assert manual['candidates'][0]['channel'] == 'SporTV'
SERVER.read_state = original_read_state

with tempfile.TemporaryDirectory() as directory:
    original_manifest = SERVER.MANIFEST
    SERVER.MANIFEST = os.path.join(directory, 'broadcasts.json')
    with open(SERVER.MANIFEST, 'w', encoding='utf-8') as f:
        json.dump({'schema': 1, 'updatedAt': '', 'events': {
            'manual:1': {'status': 'confirmed', 'broadcasters': ['Canal manual']},
            'auto:old': {'status': 'confirmed', 'broadcasters': ['Canal antigo'], 'autoGenerated': True}}}, f)
    auto = dict(probability, id='auto:new', candidates=[dict(probability['candidates'][0], channel='SporTV')])
    SERVER.publish_high_confidence([auto])
    with open(SERVER.MANIFEST, encoding='utf-8') as f:
        updated = json.load(f)['events']
    assert updated['manual:1']['broadcasters'] == ['Canal manual']
    assert 'auto:old' not in updated
    assert updated['auto:new']['autoGenerated'] is True
    SERVER.MANIFEST = original_manifest

with tempfile.TemporaryDirectory() as directory:
    original_state_file, original_manifest = SERVER.STATE_FILE, SERVER.MANIFEST
    SERVER.STATE_FILE = os.path.join(directory, 'state.json')
    SERVER.MANIFEST = os.path.join(directory, 'broadcasts.json')
    SERVER.write_state({'threshold': 75, 'runDate': '', 'forecasts': [{
        'id': 'test:review', 'title': 'São Paulo x Santos', 'start': (time.time() - 5 * 3600) * 1000,
        'candidates': [{'channel': 'SporTV', 'features': {'bothTeams': 1}}]}], 'history': [], 'observations': [], 'reviewed': {}})
    with open(SERVER.MANIFEST, 'w', encoding='utf-8') as f:
        json.dump({'schema': 1, 'updatedAt': '', 'events': {}}, f)
    http = HTTPServer(('127.0.0.1', 0), SERVER.Handler)
    threading.Thread(target=http.serve_forever, daemon=True).start()
    base = 'http://127.0.0.1:%d' % http.server_port
    outcome_req = Request(base + '/api/outcome', data=json.dumps({'id': 'test:review', 'channel': 'SporTV', 'label': 1}).encode(),
        headers={'Content-Type': 'application/json'}, method='POST')
    with urlopen(outcome_req) as response:
        assert json.load(response)['ok'] is True
    state = SERVER.read_state()
    assert len(state['observations']) == 1 and state['observations'][0]['label'] == 1
    review_req = Request(base + '/api/review', data=json.dumps({'id': 'test:review', 'action': 'confirm', 'channel': 'SporTV'}).encode(),
        headers={'Content-Type': 'application/json'}, method='POST')
    with urlopen(review_req) as response:
        assert json.load(response)['ok'] is True
    with open(SERVER.MANIFEST, encoding='utf-8') as f:
        assert json.load(f)['events']['test:review']['broadcasters'] == ['SporTV']
    http.shutdown()
    http.server_close()
    SERVER.STATE_FILE, SERVER.MANIFEST = original_state_file, original_manifest

print('Sports control EPG parsing and matching checks passed.')
